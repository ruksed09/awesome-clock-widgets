#!/usr/bin/env python3
"""
Writes the analogue widget's hands and layouts.

AnalogClock in a widget can only change its hands and colours at runtime on Android 12 and newer, so
each hand style ships as a layout in light and dark ink: WidgetRenderer picks the one that suits the
text colour, and tints it exactly on newer phones. The dial itself (marks, numerals, face) is drawn
to a bitmap by AnalogDial, which works on every version.

    python3 tools/widgets/generate_analog.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "app/src/main/res"
INKS = {"light": "#FFFFFFFF", "dark": "#FF141418"}

# style: (hour width, hour from, hour to, minute width, minute from, minute to, pivot radius)
# Coordinates are on a 200-unit dial pointing at 12, centre (100, 100).
HANDS = {
    "classic": (6.5, 108, 50, 4.0, 110, 22, 5.5),
    "slim": (3.2, 104, 54, 2.2, 106, 18, 3.6),
    "bold": (11.0, 104, 58, 7.5, 104, 26, 8.0),
}

def vector(body, comment, size=1200):
    # Drawn large so AnalogClock (which only scales down) fills any cell; VectorDrawable rasterises at
    # the on-screen size, so this costs no memory.
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/widgets/generate_analog.py. {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="200"
    android:viewportHeight="200">
{body}
</vector>
'''

def line(width, y1, y2, ink):
    return f'    <path android:strokeColor="{ink}" android:strokeWidth="{width}" android:strokeLineCap="round" android:pathData="M100,{y1} L100,{y2}" />'

def dot(r, ink):
    return f'    <path android:fillColor="{ink}" android:pathData="M100,100 m-{r},0 a{r},{r} 0,1 1,{2*r},0 a{r},{r} 0,1 1,-{2*r},0" />'

def layout(style, ink):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by tools/widgets/generate_analog.py. Analogue widget, {style} hands in {ink} ink.
  The dial is a bitmap from AnalogDial; AnalogClock draws only the hands over it and keeps time itself.
-->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/w_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent">

    <ImageView
        android:id="@+id/w_bg"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:visibility="gone" />

    <ImageView
        android:id="@+id/w_border"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:visibility="gone" />

    <FrameLayout
        android:id="@+id/w_content"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:padding="6dp">

        <ImageView
            android:id="@+id/w_dial"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:importantForAccessibility="no"
            android:scaleType="fitCenter" />

        <AnalogClock
            android:id="@+id/w_analog"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:dial="@drawable/wa_dial_blank"
            android:hand_hour="@drawable/wa_hand_{style}_hour_{ink}"
            android:hand_minute="@drawable/wa_hand_{style}_minute_{ink}" />
    </FrameLayout>
</FrameLayout>
'''

def main():
    drawable = ROOT / "drawable"
    (drawable / "wa_dial_blank.xml").write_text(vector(
        '    <path android:fillColor="#00000000" android:pathData="M0,0h200v200h-200z" />',
        "Empty dial: AnalogDial draws the real one underneath."))
    for ink, colour in INKS.items():
        for style, (hw, h1, h2, mw, m1, m2, pr) in HANDS.items():
            (drawable / f"wa_hand_{style}_hour_{ink}.xml").write_text(vector(line(hw, h1, h2, colour), f"{style} hour hand, {ink} ink."))
            (drawable / f"wa_hand_{style}_minute_{ink}.xml").write_text(
                vector(line(mw, m1, m2, colour) + "\n" + dot(pr, colour), f"{style} minute hand and pivot, {ink} ink."))
            (ROOT / "layout" / f"widget_analog_{style}_{ink}.xml").write_text(layout(style, ink))
    (drawable / "wa_hand_second.xml").write_text(vector(
        line(1.6, 118, 16, "#FFFFFFFF") + "\n" + dot(3, "#FFFFFFFF"), "Seconds hand, tinted to the accent (Android 12 and newer)."))
    print("wrote analogue hands and layouts")

if __name__ == "__main__":
    main()
