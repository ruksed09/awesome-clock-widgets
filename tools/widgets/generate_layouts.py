#!/usr/bin/env python3
"""
Writes the text widget layouts, one per typeface, to app/src/main/res/layout/widget_text_<id>.xml.

Home-screen widgets are RemoteViews: colours, formats, visibility and padding can change at runtime,
but the typeface cannot. So every typeface gets its own copy of one layout, and WidgetRenderer picks
the copy and shows the rows a style needs. Edit TYPEFACES or TEMPLATE here and run:

    python3 tools/widgets/generate_layouts.py

Keep TYPEFACES in step with WidgetTypefaces.kt (a unit test checks every id has a layout).
"""
from pathlib import Path

# id, font resource, weight of the large numerals, weight of the small lines, tracking of the numerals
TYPEFACES = [
    ("cormorant_light", "cormorant", 300, 500, 0.02),
    ("playfair", "playfair", 500, 500, 0.0),
    ("inter_thin", "inter", 200, 400, -0.02),
    ("inter_bold", "inter", 700, 500, -0.03),
    ("outfit_light", "outfit", 250, 400, 0.0),
    ("outfit_black", "outfit", 850, 500, -0.02),
    ("space_grotesk", "space_grotesk", 500, 500, -0.02),
    ("josefin_light", "josefin_sans", 300, 400, 0.04),
    ("syne_bold", "syne", 700, 500, -0.02),
    ("roboto_mono", "roboto_mono", 300, 400, -0.04),
]

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by tools/widgets/generate_layouts.py: edit the template there, not this file.
  Typeface: {id}. Every row is hidden until WidgetRenderer shows the ones a style needs; the visible
  rows share the height by weight and auto-size their text, so the widget fills any cell size.
-->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/w_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent">

    <ImageView
        android:id="@+id/w_bg"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:visibility="gone" />

    <ImageView
        android:id="@+id/w_border"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:visibility="gone" />

    <LinearLayout
        android:id="@+id/w_content"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:gravity="center"
        android:orientation="vertical"
        android:padding="6dp">
{rows}
    </LinearLayout>
</FrameLayout>
"""

def clock(view_id, weight, size_min, size_max, fmt12, fmt24, wght, tracking, caps=False, step="2sp"):
    caps_attr = '\n            android:textAllCaps="true"' if caps else ""
    return f"""
        <TextClock
            android:id="@+id/{view_id}"
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="{weight}"
            android:autoSizeMaxTextSize="{size_max}sp"
            android:autoSizeMinTextSize="{size_min}sp"
            android:autoSizeStepGranularity="{step}"
            android:autoSizeTextType="uniform"
            android:fontFamily="@font/{{font}}"
            android:fontFeatureSettings="lnum, tnum"
            android:fontVariationSettings="'wght' {wght}"
            android:format12Hour="{fmt12}"
            android:format24Hour="{fmt24}"
            android:gravity="center"
            android:includeFontPadding="false"
            android:letterSpacing="{tracking}"
            android:maxLines="1"{caps_attr}
            android:textColor="#FFFFFF"
            android:visibility="gone" />"""

def rows(big, small, tracking):
    parts = [
        clock("w_kicker", 0.62, 7, 22, "EEEE", "EEEE", small, 0.16, caps=True, step="1sp"),
        clock("w_title", 1.5, 10, 72, "EEEE", "EEEE", small, 0.0),
        clock("w_time", 3, 14, 220, "h:mm", "HH:mm", big, tracking),
        clock("w_hour", 2.3, 14, 220, "hh", "HH", big, tracking),
        clock("w_minute", 2.3, 14, 220, "mm", "mm", big, tracking),
        clock("w_day", 2.6, 14, 220, "d", "d", big, tracking),
        """
        <LinearLayout
            android:id="@+id/w_ornament_row"
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="0.5"
            android:gravity="center"
            android:orientation="horizontal"
            android:visibility="gone">

            <ImageView
                android:id="@+id/w_ornament"
                android:layout_width="wrap_content"
                android:layout_height="match_parent"
                android:adjustViewBounds="true"
                android:importantForAccessibility="no"
                android:scaleType="fitCenter" />
        </LinearLayout>""",
        clock("w_date", 0.8, 8, 30, "EEEE d MMMM", "EEEE d MMMM", small, 0.01, step="1sp"),
        clock("w_date_caps", 0.7, 7, 22, "EEEE d MMMM", "EEEE d MMMM", small, 0.18, caps=True, step="1sp"),
    ]
    return "".join(parts)

def main():
    out = Path(__file__).resolve().parents[2] / "app/src/main/res/layout"
    for tid, font, big, small, tracking in TYPEFACES:
        body = rows(big, small, tracking).replace("{font}", font)
        (out / f"widget_text_{tid}.xml").write_text(TEMPLATE.format(id=tid, rows=body))
    print(f"wrote {len(TYPEFACES)} layouts to {out}")

if __name__ == "__main__":
    main()
